package com.kalogsc.feedbil.domain

/**
 * The data a share action wants to send, before it is turned into text.
 *
 * The URL is always validated by the caller before it gets here. Keeping the
 * content as data (rather than a finished string) lets the screen resolve the
 * localized "Sem título" fallback and keeps this type unit-testable on the JVM.
 */
sealed interface ShareContent {
    data class Normal(val title: String?, val url: String) : ShareContent
    data class Ai(val summary: String, val url: String) : ShareContent
}

/**
 * Builds the plain text sent through the Android Sharesheet.
 *
 * The only words in the output come from the caller: the localized title
 * fallback. Separators are layout, not UI strings. AI sharing deliberately has
 * no "generated by AI" marker in the shared text (an approved override recorded
 * in `DECISIONS.md`); the article screen still labels generated summaries.
 */
object ShareTextBuilder {

    fun build(content: ShareContent, untitled: String): String = when (content) {
        is ShareContent.Normal -> listOf(resolveTitle(content.title, untitled), content.url)
            .joinToString("\n")

        is ShareContent.Ai -> listOf(content.summary, content.url)
            .joinToString("\n\n")
    }

    private fun resolveTitle(title: String?, untitled: String): String =
        title?.trim()
            ?.takeIf { it.isNotEmpty() }
            // Feed titles are untrusted: a newline must not inject extra lines
            // into the shared text.
            ?.replace(LINE_BREAK, " ")
            ?: untitled

    private val LINE_BREAK = Regex("\\r?\\n")
}
